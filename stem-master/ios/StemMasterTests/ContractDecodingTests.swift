import Foundation
import XCTest
@testable import StemMaster

/// Decodes `stem-master/contract/job_completed.json`, a real completed Job written by the server
/// test-suite (SPEC section 4), so any drift between server and app fails CI.
final class ContractDecodingTests: XCTestCase {
    private static let missingMessage = """
    contract/job_completed.json is missing from the StemMasterTests bundle. It is generated by \
    the server test-suite (run `pytest` in stem-master/server); then regenerate the Xcode project \
    with `xcodegen generate` in stem-master/ios so the file is copied into the test bundle.
    """

    private func contractData() throws -> Data {
        let url = try XCTUnwrap(Fixtures.url("job_completed", ext: "json"), Self.missingMessage)
        return try Data(contentsOf: url)
    }

    private func contractJob() throws -> Job {
        try StemMasterJSON.makeDecoder().decode(Job.self, from: contractData())
    }

    private func contractObject() throws -> [String: Any] {
        let object = try JSONSerialization.jsonObject(with: contractData())
        return try XCTUnwrap(object as? [String: Any], "job_completed.json must be a JSON object")
    }

    func testDecodesCompletedJob() throws {
        let job = try contractJob()

        XCTAssertEqual(job.status, .completed)
        XCTAssertNotEqual(job.stage, .unknown, "stage must be a known stage id")
        XCTAssertEqual(job.progress, 1, accuracy: 1e-9)
        XCTAssertEqual(job.id.count, 32)
        XCTAssertTrue(job.id.allSatisfy { "0123456789abcdef".contains($0) }, "id must be 32 lowercase hex chars")
        XCTAssertFalse(job.filename.isEmpty)
        XCTAssertNil(job.error)
        XCTAssertNil(job.queuePosition)
        XCTAssertLessThanOrEqual(job.createdAt, job.updatedAt)
        XCTAssertEqual(job.zipURL, "/v1/jobs/\(job.id)/download.zip")
        XCTAssertTrue(job.gainOffsetDB.isFinite)
        XCTAssertLessThanOrEqual(job.gainOffsetDB, 0, "the common gain only ever lowers the stems")

        let analysis = try XCTUnwrap(job.analysis, "a completed job carries its analysis")
        XCTAssertGreaterThan(analysis.durationSeconds, 0)
        XCTAssertGreaterThan(analysis.sampleRate, 0)
        XCTAssertGreaterThan(analysis.channels, 0)
        XCTAssertTrue((0...1).contains(analysis.artifactLevel))
        XCTAssertNotEqual(analysis.artifactLabel, .unknown)
        XCTAssertTrue((0...1).contains(analysis.bpmConfidence))
        XCTAssertTrue((0...1).contains(analysis.keyConfidence))
        XCTAssertFalse(analysis.key.isEmpty)

        XCTAssertFalse(job.stems.isEmpty)
        for stem in job.stems {
            XCTAssertTrue(StemCatalog.orderedIDs.contains(stem.id), "unknown stem id \(stem.id)")
            XCTAssertNotEqual(stem.group, .unknown, "\(stem.id): unknown group")
            XCTAssertNotEqual(stem.role, .unknown, "\(stem.id): unknown role")
            XCTAssertNotNil(HexColor.parse(stem.color), "\(stem.id): bad colour \(stem.color)")
            XCTAssertEqual(stem.waveform.count, 256, "\(stem.id): waveform must have 256 points")
            XCTAssertTrue(stem.waveform.allSatisfy { (0...1).contains($0) }, "\(stem.id): waveform out of 0...1")
            XCTAssertEqual(stem.wavURL, "/v1/jobs/\(job.id)/stems/\(stem.id).wav")
            XCTAssertEqual(stem.previewURL, "/v1/jobs/\(job.id)/stems/\(stem.id).m4a")
            XCTAssertGreaterThan(stem.wavBytes, 0, "\(stem.id): wav_bytes")
            XCTAssertGreaterThan(stem.previewBytes, 0, "\(stem.id): preview_bytes")
            XCTAssertTrue((0...1).contains(stem.activeRatio))
            XCTAssertTrue(stem.peakDBFS.isFinite && stem.rmsDBFS.isFinite)
        }
        XCTAssertEqual(job.stems.map(\.id), StemCatalog.sorted(job.stems).map(\.id), "manifest must be in catalogue order")
        XCTAssertEqual(Set(job.stems.map(\.id)).count, job.stems.count, "stem ids must be unique")
        XCTAssertTrue(job.stems.contains { $0.role == .primary })
        for required in ["vocals", "drums", "bass", "guitar", "piano", "other"] {
            XCTAssertTrue(job.stems.contains { $0.id == required }, "\(required) is always delivered (SPEC section 3)")
        }
    }

    func testOptionalStemsMatchOptions() throws {
        let job = try contractJob()
        let ids = Set(job.stems.map(\.id))
        let roles = Dictionary(uniqueKeysWithValues: job.stems.map { ($0.id, $0.role) })
        if job.options.drumSplit {
            XCTAssertEqual(roles["drums"], .bus, "drums is a bus when the kit is split")
            for part in ["kick", "snare", "toms", "hihat", "ride", "crash"] {
                XCTAssertTrue(ids.contains(part), "drum split must deliver \(part)")
            }
        } else {
            XCTAssertEqual(roles["drums"], .primary)
        }
        if job.options.vocalSplit {
            XCTAssertTrue(ids.contains("lead_vocals") && ids.contains("backing_vocals"))
        }
        if job.options.vocalSplit || job.options.dereverb {
            XCTAssertEqual(roles["vocals"], .bus)
        } else {
            XCTAssertEqual(roles["vocals"], .primary)
        }
        XCTAssertEqual(ids.contains("removed_bleed"), job.options.cleanup)
        XCTAssertEqual(ids.contains("removed_noise"), job.options.denoise)
        for stem in job.stems where stem.group == .removed {
            XCTAssertEqual(stem.role, .removed)
        }
    }

    /// Every key the server sends must be a key the app models, and vice versa.
    func testContractKeysMatchModels() throws {
        let object = try contractObject()
        XCTAssertEqual(Set(object.keys), Set(Job.CodingKeys.allCases.map(\.rawValue)), "Job keys drifted")

        let options = try XCTUnwrap(object["options"] as? [String: Any])
        XCTAssertEqual(Set(options.keys), Set(JobOptions.CodingKeys.allCases.map(\.rawValue)), "JobOptions keys drifted")

        let analysis = try XCTUnwrap(object["analysis"] as? [String: Any])
        XCTAssertEqual(Set(analysis.keys), Set(Analysis.CodingKeys.allCases.map(\.rawValue)), "Analysis keys drifted")

        let stems = try XCTUnwrap(object["stems"] as? [[String: Any]])
        XCTAssertFalse(stems.isEmpty)
        let stemKeys = Set(Stem.CodingKeys.allCases.map(\.rawValue))
        for stem in stems {
            XCTAssertEqual(Set(stem.keys), stemKeys, "Stem keys drifted (\(stem["id"] ?? "?"))")
        }
    }

    /// The enums the server sends must all be ones this build knows.
    func testContractEnumsAreKnown() throws {
        let object = try contractObject()
        XCTAssertNotNil(JobStatus(rawValue: object["status"] as? String ?? ""))
        XCTAssertNotNil(JobStage(rawValue: object["stage"] as? String ?? ""))
        let options = try XCTUnwrap(object["options"] as? [String: Any])
        XCTAssertNotNil(Quality(rawValue: options["quality"] as? String ?? ""))
        XCTAssertNotNil(Strength(rawValue: options["cleanup_strength"] as? String ?? ""))
        XCTAssertNotNil(Strength(rawValue: options["denoise_strength"] as? String ?? ""))
        XCTAssertNotNil(OutputFormat(rawValue: options["output_format"] as? String ?? ""))
        let stems = try XCTUnwrap(object["stems"] as? [[String: Any]])
        for stem in stems {
            XCTAssertNotNil(StemGroup(rawValue: stem["group"] as? String ?? ""))
            XCTAssertNotNil(StemRole(rawValue: stem["role"] as? String ?? ""))
        }
    }

    /// `job.json` on disk uses the app's encoder; it must round-trip losslessly.
    func testPersistenceRoundTrip() throws {
        let job = try contractJob()
        let data = try StemMasterJSON.makeEncoder().encode(job)
        let again = try StemMasterJSON.makeDecoder().decode(Job.self, from: data)
        XCTAssertEqual(again, job)
    }

    func testMixerLayoutFromContract() throws {
        let job = try contractJob()
        let layout = MixerLayout(stems: job.stems)
        let order = layout.sections.map(\.group)
        XCTAssertEqual(order.first, .vocals, "Vocals section comes first")
        let expectedOrder = StemCatalog.groupOrder.filter { order.contains($0) }
        XCTAssertEqual(order, expectedOrder)
        XCTAssertTrue(layout.removed.allSatisfy { $0.role == .removed })
        XCTAssertTrue(layout.sections.allSatisfy { $0.playable.allSatisfy { $0.role == .primary } })
        XCTAssertTrue(layout.sections.allSatisfy { $0.buses.allSatisfy { $0.role == .bus } })
        XCTAssertEqual(Set(layout.playableStems.map(\.id)), Set(job.playableStems.map(\.id)))
        XCTAssertFalse(layout.playableStems.contains { $0.role == .bus }, "buses never load into the mixer")
    }
}
